#!/usr/bin/env python3
"""Objectives, epic events and Jedi Tests in the V-card decks, with their Dojo coverage -> data/schedules/v-cards/CONTENTS.md.

    python3 tools/vcard_contents.py --card-db PATH/card_blueprint_database-7eee2c8....json > data/schedules/v-cards/CONTENTS.md

--card-db: a Gemp card database export that knows the V cards (lab: data/cards/card_blueprint_database-7eee2c8fc8a2221a0425617c5cc4451ca7b88d81.json,
from scripts/export_card_database.py on the V-card engine). Decks: reports/data/v-cards/decks.json; Dojo rewards:
data/dojo/rewards.json.
"""
import argparse
import collections
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATS = {'OBJECTIVE': 'objective', 'EPIC_EVENT': 'epic event', 'JEDI_TEST': 'Jedi Test'}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--card-db', type=Path, required=True)
    a = ap.parse_args()
    db = {r['cardId']: r for r in json.loads(a.card_db.read_text())}
    decks = json.loads((ROOT / 'reports/data/v-cards/decks.json').read_text())['decks']
    covered = {k.split('~')[0] for k in json.loads((ROOT / 'data/dojo/rewards.json').read_text())['items']}
    cnt = {c: collections.defaultdict(collections.Counter) for c in CATS}
    side, none, anyepic = {}, collections.Counter(), 0
    for d in decks:
        ids = set(re.findall(r'blueprintId="([^"]+)"', (ROOT / d['deck']).read_text()))
        found = {c: {i for i in ids if db.get(i, {}).get('cardCategory') == c} for c in CATS}
        if not found['OBJECTIVE']:
            none[d['side']] += 1
        anyepic += bool(found['EPIC_EVENT'])
        for c, s in found.items():
            for i in s:
                cnt[c][i][d['split']] += 1
                side[i] = d['side']

    def table(c):
        out = []
        for sd in ('DARK', 'LIGHT'):
            items = sorted([(sum(v.values()), i, v) for i, v in cnt[c].items() if side[i] == sd],
                           key=lambda x: (-x[0], db[x[1]]['title']))
            if not items:
                continue
            name = CATS[c] + ('s' if len(items) > 1 else '')
            out += [f"\n### {sd.title()} Side — {len(items)} {name}, {sum(x[0] for x in items)} decks\n",
                    f"| # | {CATS[c][0].upper() + CATS[c][1:]} | ID | Decks | Gathering | Held out | Dojo reward |",
                    "|---|---|---|---:|---:|---:|---|"]
            out += [f"| {n} | {db[i]['title']} | `{i}` | {t} | {v['gathering']} | {v['heldout']} | "
                    f"{'yes' if i in covered else '**no**'} |" for n, (t, i, v) in enumerate(items, 1)]
        return "\n".join(out)

    unc = {c: sorted(i for i in cnt[c] if i not in covered) for c in CATS}
    print("# Objectives, epic events and Jedi Tests in the 927 V-card decks\n")
    print("Generated by `tools/vcard_contents.py`. Counts are decks holding the card (at least one copy), split into the "
          "gathering (743) and held-out (184) decks; card categories from Gemp's V-era card database export. **Dojo "
          "reward** = the card has an entry in `data/dojo/rewards.json`; `v31_stage.py` refuses a training pool holding an "
          "objective, epic event or Jedi Test without one (`scripts/dojo_coverage.py`). The first V-card "
          "training run (lab plan dojo-v-cards: `models/vcards-vct`) trained on the gathering decks.\n")
    print(f"**Summary:** {len(cnt['OBJECTIVE'])} objectives in {len(decks) - sum(none.values())} decks; "
          f"**{sum(none.values())} decks have no objective** (DS {none['DARK']}, LS {none['LIGHT']}). "
          f"{len(cnt['EPIC_EVENT'])} epic events in {anyepic} decks; {len(cnt['JEDI_TEST'])} Jedi Tests. "
          f"Without a Dojo reward: {len(unc['OBJECTIVE'])} objectives, {len(unc['EPIC_EVENT'])} epic events, "
          f"{len(unc['JEDI_TEST'])} Jedi Test(s) = {sum(map(len, unc.values()))} items blocking V training.")
    print("\n## Objectives")
    print(table('OBJECTIVE'))
    print("\n## Epic events")
    print(table('EPIC_EVENT'))
    print("\n## Jedi Tests")
    print(table('JEDI_TEST'))
    print("\nSame-title objectives with different IDs (an original card and its V version) are counted separately. "
          "`decks.json`'s summary says 52 objectives; the card lists give the count above (not reconciled).")


if __name__ == '__main__':
    main()
